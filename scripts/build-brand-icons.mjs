#!/usr/bin/env bun
/**
 * Generates React components from the SVGs in public/brand/.
 *
 * The SVG files are the single source of truth: re-export from Figma, run
 * `bun run brand`, and the components update. Nothing is hand-pasted.
 *
 * Fills are normalised to currentColor so each component inherits the text
 * color of wherever it's used. Gradient-filled sources are skipped — they
 * can't inherit, and a lockup that ignores currentColor is a footgun.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const SRC = "public/brand";
const OUT = "components/brand";

/** Turns "lockup-gradient" into "LockupGradient". */
function toPascalCase(name) {
  return name
    .split(/[-_\s]+/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/** Pulls the viewBox out of the root <svg>, falling back to width/height. */
function readViewBox(svg) {
  const explicit = svg.match(/viewBox="([^"]+)"/);
  if (explicit) return explicit[1];

  const w = svg.match(/width="(\d+(?:\.\d+)?)"/);
  const h = svg.match(/height="(\d+(?:\.\d+)?)"/);
  if (w && h) return `0 0 ${w[1]} ${h[1]}`;

  throw new Error("no viewBox and no width/height to derive one from");
}

/**
 * Extracts drawable elements, normalising every real fill to currentColor.
 * fill="none" is preserved — it's a stroke/no-paint hint, not a color.
 */
function extractShapes(svg) {
  const shapes = [];
  const pattern = /<(path|rect|circle|ellipse|polygon|polyline)\b([^>]*?)\/?>/g;

  for (const [, tag, rawAttrs] of svg.matchAll(pattern)) {
    // Skip the root element's own fill="none" passthrough.
    const attrs = rawAttrs.trim();
    if (!attrs) continue;

    const fill = attrs.match(/fill="([^"]*)"/)?.[1];
    if (fill?.startsWith("url(")) {
      return { unsupported: `gradient fill (${fill})` };
    }

    // Drop the fill we're about to replace, keep everything else (d, rx, …).
    const rest = attrs
      .replace(/\s*fill="[^"]*"/g, "")
      .replace(/\s+/g, " ")
      .trim();

    const nextFill = fill === "none" ? "none" : "currentColor";
    shapes.push(`<${tag} fill="${nextFill}"${rest ? " " + rest : ""} />`);
  }

  return { shapes };
}

function renderComponent(componentName, viewBox, shapes) {
  const body = shapes.map((s) => `      ${s}`).join("\n");

  return `// Generated by scripts/build-brand-icons.mjs — do not edit by hand.
// Source: public/brand/*.svg. Run \`bun run brand\` to regenerate.

import type { SVGProps } from "react";

/**
 * Defaults to an accessible name — a path-only SVG is invisible to screen
 * readers otherwise. Pass \`aria-hidden\` (or your own label) to override
 * when the mark is decorative next to real text.
 */
export function ${componentName}({
  title = "Riffle",
  ...props
}: SVGProps<SVGSVGElement> & { title?: string }) {
  // aria-hidden="false" is a string and therefore truthy — compare against
  // the values that actually mean hidden.
  const hidden = props["aria-hidden"] === true || props["aria-hidden"] === "true";
  const labelled = hidden ? {} : { role: "img", "aria-label": title };

  return (
    <svg
      viewBox="${viewBox}"
      xmlns="http://www.w3.org/2000/svg"
      {...labelled}
      {...props}
    >
${body}
    </svg>
  );
}
`;
}

const files = (await readdir(SRC)).filter((f) => f.endsWith(".svg")).sort();
if (files.length === 0) {
  console.error(`no .svg files in ${SRC}/`);
  process.exit(1);
}

const written = [];
const skipped = [];

for (const file of files) {
  const slug = file.replace(/\.svg$/, "");
  const componentName = toPascalCase(slug);
  const svg = await readFile(join(SRC, file), "utf8");

  let viewBox;
  try {
    viewBox = readViewBox(svg);
  } catch (error) {
    skipped.push([file, error.message]);
    continue;
  }

  const { shapes, unsupported } = extractShapes(svg);
  if (unsupported) {
    skipped.push([file, `${unsupported} cannot inherit currentColor`]);
    continue;
  }
  if (shapes.length === 0) {
    skipped.push([file, "no drawable shapes found"]);
    continue;
  }

  const outFile = join(OUT, `${slug}.tsx`);
  await writeFile(outFile, renderComponent(componentName, viewBox, shapes));
  written.push([outFile, componentName, shapes.length, slug]);
}

if (written.length === 0) {
  console.error(
    `no components generated from ${SRC}/ — refusing to overwrite the barrel`,
  );
  for (const [file, why] of skipped) console.error(`  skipped ${file}: ${why}`);
  process.exit(1);
}

// Barrel file so consumers import from one place.
const barrel = written
  .map(([, name, , slug]) => `export { ${name} } from "./${slug}";`)
  .join("\n");
await writeFile(join(OUT, "index.ts"), `${barrel}\n`);

for (const [file, name, count] of written) {
  console.log(`  ${name.padEnd(16)} ${String(count).padStart(2)} shapes  ${file}`);
}
for (const [file, why] of skipped) {
  console.log(`  skipped ${file}: ${why}`);
}
console.log(`\n${written.length} component(s) + index.ts`);
