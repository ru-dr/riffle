// Compiles the docs' markdown into one generated module, so pages import
// their content statically instead of reading files at request time. Reading
// from a computed path made Turbopack trace the whole project into the docs
// route's server bundle.
//
// Sources: every page in site/content/docs, plus files the repository already
// maintains (the configuration reference), listed in SOURCES. Runs before
// `dev` and `build`; the output is gitignored.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const SOURCES = { "../contracts/REFERENCE.md": join(root, "..", "contracts", "REFERENCE.md") };

const out = {};
for (const f of (await readdir(join(root, "content", "docs"))).filter((f) => f.endsWith(".md")).sort()) {
  out[f] = await readFile(join(root, "content", "docs", f), "utf8");
}
for (const [key, path] of Object.entries(SOURCES)) out[key] = await readFile(path, "utf8");

const body = `// Generated by scripts/build-docs.mjs. Do not edit; edit content/docs/*.md.\nexport const DOCS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
await writeFile(join(root, "components", "docs", "content.generated.ts"), body);
console.log(`docs: ${Object.keys(out).length} files compiled`);
